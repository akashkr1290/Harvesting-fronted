"""Regenerates lib/l10n/simple_strings.dart from the strings_*.py tables.

    python3 tool/l10n/generate.py

Edit a translation in the matching strings_*.py file (one key per line), then run this.
It checks that every language has every key and the same {placeholders} as English.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings_en_hi_mr import S  # noqa: E402
from strings_te_ta import TE, TA  # noqa: E402
from strings_gu_kn import GU, KN  # noqa: E402
from strings_bn_as import BN, AS  # noqa: E402

langs = {'en': {k: v[0] for k, v in S.items()}, 'hi': {k: v[1] for k, v in S.items()},
         'mr': {k: v[2] for k, v in S.items()}, 'te': TE, 'ta': TA, 'gu': GU, 'kn': KN, 'bn': BN, 'as': AS}
problems = []
for lang, table in langs.items():
    missing, extra = set(S) - set(table), set(table) - set(S)
    if missing or extra:
        problems.append(f'{lang}: missing {sorted(missing)} extra {sorted(extra)}')
    for k, v in table.items():
        if k in S and set(re.findall(r'\{(\w+)\}', v)) != set(re.findall(r'\{(\w+)\}', S[k][0])):
            problems.append(f'{lang}.{k}: placeholders differ from English')
if problems:
    sys.exit('\n'.join(problems))


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


out = ['// GENERATED by tool/l10n/generate.py from tool/l10n/strings_*.py. Do not edit by hand.',
       '// Simple-mode texts in the 9 app languages. English, Hindi and Marathi were written first;',
       '// Telugu, Tamil, Gujarati, Kannada, Bengali and Assamese should be reviewed by native speakers.',
       '// Placeholders like {name} are filled by LocalizationService.tf().', '',
       'const Map<String, Map<String, String>> simpleStrings = {']
for lang, table in langs.items():
    out.append(f"  '{lang}': {{")
    out += [f"    '{k}': {dart(table[k])}," for k in sorted(table)]
    out.append('  },')
out.append('};')
target = os.path.join(HERE, '..', '..', 'lib', 'l10n', 'simple_strings.dart')
with open(target, 'w', encoding='utf-8') as f:
    f.write('\n'.join(out) + '\n')
print(f'Wrote {os.path.normpath(target)}: {len(S)} keys x {len(langs)} languages')
